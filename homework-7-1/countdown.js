// викликаємо рекурсивну функцію лічильника
function countdown(num) {
  // виводимо поточне значення
  console.log(num);

  // базова умова зупинки рекурсії
  if (num <= 0) {
    return; 
  }

  // викликаємо саму себе зі зменшеним числом
  countdown(num - 1);
}

// старт лічильник з 5
countdown(5);